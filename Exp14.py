#Demonstrate elif statement
marks = int(input("Enter your Marks (Out of 100) : "))

if marks > 90 :
    print ("Your Grade: A+ \n")

elif marks > 80 :
    print ("Your Grade: A \n")

elif marks > 70 :
    print ("Your Grade: B \n")

elif marks > 60 :
    print ("Your Grade: C \n")

else :
    print ("Fail \n")